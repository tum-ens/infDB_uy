const LOCALES = { en: "en-US", de: "de-DE", es: "es-UY" };

function detectLang() {
  try {
    const saved = localStorage.getItem("infdb-uy-lang");
    if (saved && I18N[saved]) return saved;
  } catch (_) { /* storage unavailable */ }
  const nav = (navigator.language || "en").slice(0, 2);
  return I18N[nav] ? nav : "en";
}
const LANG = detectLang();

/** Translate `key`, substituting {name} placeholders from `vars` (values inserted as given). */
function t(key, vars) {
  const s = I18N[LANG][key] ?? I18N.en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : s;
}

function setLang(lang) {
  try { localStorage.setItem("infdb-uy-lang", lang); } catch (_) { /* storage unavailable */ }
  location.reload();
}

/** Apply translations to static markup: data-i18n (text), data-i18n-title, data-i18n-placeholder. */
function applyI18n(root = document) {
  document.documentElement.lang = LANG;
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
}
